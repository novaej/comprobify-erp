-- FR-DOC-3. Generated by subscriptionStatusTriggerBody() from SUBSCRIPTION_TRANSITIONS (rule 17);
-- the subscription periods integration test fails if this copy and the definition differ.
CREATE FUNCTION public.app_subscription_status_check() RETURNS trigger
  LANGUAGE plpgsql AS $$
BEGIN
IF NEW.status IS DISTINCT FROM OLD.status AND NOT (CASE OLD.status
    WHEN 'ACTIVE' THEN NEW.status IN ('CANCELLED', 'PAST_DUE')
    WHEN 'CANCELLED' THEN NEW.status IN ('ACTIVE')
    WHEN 'PAST_DUE' THEN NEW.status IN ('ACTIVE')
    ELSE false
  END) THEN
    RAISE EXCEPTION 'Subscription status % can not become %', OLD.status, NEW.status
      USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$$;--> statement-breakpoint
CREATE TRIGGER subscription_status_check BEFORE UPDATE OF status ON subscriptions
  FOR EACH ROW EXECUTE FUNCTION app_subscription_status_check();--> statement-breakpoint
