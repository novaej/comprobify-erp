-- FR-DOC-3. Generated by cardAttemptStatusTriggerBody() from CARD_ATTEMPT_TRANSITIONS (rule 17);
-- the Payphone integration test fails if this copy and the definition differ.
CREATE FUNCTION public.app_card_attempt_status_check() RETURNS trigger
  LANGUAGE plpgsql AS $$
BEGIN
IF NEW.status IS DISTINCT FROM OLD.status AND NOT (CASE OLD.status
    WHEN 'PENDING' THEN NEW.status IN ('APPROVED', 'CANCELLED', 'EXPIRED', 'DUPLICATE', 'ERROR')
    WHEN 'APPROVED' THEN NEW.status IN ('DUPLICATE')
    WHEN 'CANCELLED' THEN false
    WHEN 'EXPIRED' THEN false
    WHEN 'DUPLICATE' THEN false
    WHEN 'ERROR' THEN false
    ELSE false
  END) THEN
    RAISE EXCEPTION 'Card attempt status % can not become %', OLD.status, NEW.status
      USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$$;--> statement-breakpoint
