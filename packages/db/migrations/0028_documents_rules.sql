-- FR-DOC-3. Generated by documentStatusTriggerBody() from DOCUMENT_TRANSITIONS (rule 17);
-- the documents integration test fails if this copy and the definition differ.
CREATE FUNCTION public.app_document_status_check() RETURNS trigger
  LANGUAGE plpgsql AS $$
BEGIN
IF NEW.status IS DISTINCT FROM OLD.status AND NOT (CASE OLD.status
    WHEN 'SIGNED' THEN NEW.status IN ('PENDING_SEND')
    WHEN 'PENDING_SEND' THEN NEW.status IN ('RECEIVED', 'RETURNED', 'SEND_FAILED')
    WHEN 'RECEIVED' THEN NEW.status IN ('AUTHORIZED', 'NOT_AUTHORIZED')
    WHEN 'RETURNED' THEN NEW.status IN ('SIGNED')
    WHEN 'SEND_FAILED' THEN NEW.status IN ('RECEIVED', 'PENDING_SEND', 'SIGNED')
    WHEN 'AUTHORIZED' THEN NEW.status IN ('VOIDED')
    WHEN 'NOT_AUTHORIZED' THEN NEW.status IN ('SIGNED')
    WHEN 'VOIDED' THEN false
    ELSE false
  END) THEN
    RAISE EXCEPTION 'Document status % can not become %', OLD.status, NEW.status
      USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$$;
--> statement-breakpoint
CREATE TRIGGER document_status_check BEFORE UPDATE OF status ON documents
  FOR EACH ROW EXECUTE FUNCTION app_document_status_check();
