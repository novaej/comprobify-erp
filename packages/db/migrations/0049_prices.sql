-- FR-BILL-6: a published price is history, so nothing about it changes again. Only a draft's
-- amount moves, and publishing sets its date once.
CREATE FUNCTION public.app_price_frozen() RETURNS trigger
  LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.status <> 'DRAFT' THEN
    RAISE EXCEPTION 'A % price can not change', OLD.status USING ERRCODE = '23514';
  END IF;
  IF NEW.kind IS DISTINCT FROM OLD.kind OR NEW.plan_id IS DISTINCT FROM OLD.plan_id
     OR NEW.module_id IS DISTINCT FROM OLD.module_id OR NEW.pack_size IS DISTINCT FROM OLD.pack_size THEN
    RAISE EXCEPTION 'A price can not move to another thing sold' USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$$;--> statement-breakpoint
CREATE TRIGGER price_frozen BEFORE UPDATE ON prices
  FOR EACH ROW EXECUTE FUNCTION app_price_frozen();
