-- FR-DOC-3. Generated by priceStatusTriggerBody() from PRICE_TRANSITIONS (rule 17); the prices
-- integration test fails if this copy and the definition differ.
CREATE FUNCTION public.app_price_status_check() RETURNS trigger
  LANGUAGE plpgsql AS $$
BEGIN
IF NEW.status IS DISTINCT FROM OLD.status AND NOT (CASE OLD.status
    WHEN 'DRAFT' THEN NEW.status IN ('PUBLISHED', 'DISCARDED')
    WHEN 'PUBLISHED' THEN false
    WHEN 'DISCARDED' THEN false
    ELSE false
  END) THEN
    RAISE EXCEPTION 'Price status % can not become %', OLD.status, NEW.status
      USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$$;--> statement-breakpoint
