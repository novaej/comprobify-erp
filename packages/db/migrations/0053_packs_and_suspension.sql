-- Only the operator suspends or reactivates: a company's own settings write can never lift it.
-- A trigger, as RLS would let a refused UPDATE succeed quietly (mistake 29).
CREATE FUNCTION public.app_tenant_suspension_guard() RETURNS trigger
  LANGUAGE plpgsql AS $$
BEGIN
  IF (NEW.status, NEW.suspension_reason, NEW.suspended_at)
       IS DISTINCT FROM (OLD.status, OLD.suspension_reason, OLD.suspended_at)
     AND NOT public.app_is_system() THEN
    RAISE EXCEPTION 'Suspension on % needs system context', TG_TABLE_NAME
      USING ERRCODE = '42501';
  END IF;
  RETURN NEW;
END;
$$;--> statement-breakpoint
