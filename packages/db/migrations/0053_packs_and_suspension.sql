-- FR-DOC-3. Generated by packStatusTriggerBody() from PACK_TRANSITIONS (rule 17); the packs
-- integration test fails if this copy and the definition differ.
CREATE FUNCTION public.app_pack_status_check() RETURNS trigger
  LANGUAGE plpgsql AS $$
BEGIN
IF NEW.status IS DISTINCT FROM OLD.status AND NOT (CASE OLD.status
    WHEN 'ACTIVE' THEN NEW.status IN ('REFUNDED')
    WHEN 'REFUNDED' THEN false
    ELSE false
  END) THEN
    RAISE EXCEPTION 'Pack status % can not become %', OLD.status, NEW.status
      USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$$;--> statement-breakpoint
