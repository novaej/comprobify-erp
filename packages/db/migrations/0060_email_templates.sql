-- A published version is history, so nothing about it changes again. Only a draft's copy moves,
-- and publishing sets its date and author once.
CREATE FUNCTION public.app_email_template_frozen() RETURNS trigger
  LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.status <> 'DRAFT' THEN
    RAISE EXCEPTION 'A % email template can not change', OLD.status USING ERRCODE = '23514';
  END IF;
  IF NEW.template IS DISTINCT FROM OLD.template OR NEW.locale IS DISTINCT FROM OLD.locale
     OR NEW.version IS DISTINCT FROM OLD.version THEN
    RAISE EXCEPTION 'An email template can not move to another version' USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$$;--> statement-breakpoint
CREATE TRIGGER email_template_frozen BEFORE UPDATE ON email_templates
  FOR EACH ROW EXECUTE FUNCTION app_email_template_frozen();--> statement-breakpoint
