-- FR-DOC-3. Generated by emailTemplateStatusTriggerBody() from EMAIL_TEMPLATE_TRANSITIONS (rule
-- 17); the email templates integration test fails if this copy and the definition differ.
CREATE FUNCTION public.app_email_template_status_check() RETURNS trigger
  LANGUAGE plpgsql AS $$
BEGIN
IF NEW.status IS DISTINCT FROM OLD.status AND NOT (CASE OLD.status
    WHEN 'DRAFT' THEN NEW.status IN ('PUBLISHED', 'DISCARDED')
    WHEN 'PUBLISHED' THEN false
    WHEN 'DISCARDED' THEN false
    ELSE false
  END) THEN
    RAISE EXCEPTION 'Email template status % can not become %', OLD.status, NEW.status
      USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$$;--> statement-breakpoint
