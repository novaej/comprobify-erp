// Writes src/sri/xsd/*.ts from assets/xsd/*.xsd, so each schema has one source and the
// build needs no file reads (ADR-013). Run: pnpm --filter @comprobify/core xsd:embed
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SCHEMAS = {
  'factura_V2.1.0.xsd': ['factura-2.1.0.ts', 'The factura XSD 2.1.0'],
  'nota_credito_V1.1.0.xsd': ['nota-credito-1.1.0.ts', 'The nota de crédito XSD 1.1.0'],
  'guia_remision_V1.1.0.xsd': ['guia-remision-1.1.0.ts', 'The guía de remisión XSD 1.1.0'],
  'xmldsig-core-schema.xsd': ['xmldsig-core.ts', 'The XML signature XSD the others import'],
};

for (const [file, [target, what]] of Object.entries(SCHEMAS)) {
  const xsd = readFileSync(join(root, 'assets/xsd', file), 'utf8');
  if (xsd.includes('`') || xsd.includes('${')) throw new Error(`${file} can't sit in a template`);
  const header = `// ${what} as SRI publishes it, byte for byte, from assets/xsd/${file}.\n// Generated by scripts/embed-xsd.mjs; xsd-assets.test.ts fails if it differs from the file.\n`;
  writeFileSync(
    join(root, 'src/sri/xsd', target),
    `${header}export default String.raw\`${xsd}\`;\n`,
  );
}
