import { companyAgreement } from '@comprobify/core';
import MarkdownIt from 'markdown-it';
import { notFound } from 'next/navigation';
import { getTranslations, setRequestLocale } from 'next-intl/server';
import { PageHeader } from '@/components/page-header';
import { getRuntime } from '@/server/runtime';
import { loadShell } from '@/server/shell';
import { pageTitle } from '@/server/page-title';

export const generateMetadata = pageTitle('legalDocument');

const TYPES = { terms: 'TERMS', privacy: 'PRIVACY', dpa: 'DPA' } as const;

// Raw HTML off: the texts are Markdown only, so nothing in them can inject markup.
const markdown = new MarkdownIt({ html: false, linkify: true });

// The company's own copy: personalized, or exactly as accepted.
export default async function LegalDocumentPage({
  params,
}: {
  params: Promise<{ locale: string; type: string }>;
}) {
  const { locale, type } = await params;
  setRequestLocale(locale);
  const documentType = TYPES[type as keyof typeof TYPES];
  if (!documentType) notFound();
  const { actor } = await loadShell(locale);
  const { db, agreementParties } = await getRuntime();
  if (!agreementParties) notFound();
  const copy = await companyAgreement(actor, db, documentType, agreementParties);
  if (!copy) notFound();
  const t = await getTranslations('legal');

  // The page header is the title, so the text's own first heading isn't shown twice.
  // Only the display drops it; the stored copy stays exactly as accepted.
  const body = copy.markdown.replace(/^# .*\n+/, '');
  return (
    <div className="max-w-3xl">
      <PageHeader
        title={t(`types.${documentType}`)}
        description={t('version', { version: copy.version })}
        backHref="/legal"
        backLabel={t('title')}
      />
      <article className="prose-legal [&>div>:first-child]:mt-0 rounded-xl border border-border bg-card p-6 text-sm leading-relaxed shadow-sm sm:p-8">
        {/* Generated by markdown-it with HTML disabled. */}
        <div dangerouslySetInnerHTML={{ __html: markdown.render(body) }} />
      </article>
    </div>
  );
}
